const { chromium } = require('playwright');
const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
(async () => {
  const browser = await chromium.launch({ channel: 'msedge', headless: true });
  const errors = [];
  const base = 'http://localhost:4173';
  const passwords = Object.fromEntries(fs.readFileSync(path.join(__dirname, '../data/bootstrap-credentials.txt'), 'utf8').trim().split('\n').map(line => line.split(': ')));
  fs.mkdirSync(path.join(__dirname, '../test-results'), { recursive: true });
  const adminContext = await browser.newContext(); const admin = await adminContext.newPage();
  admin.on('pageerror', e => errors.push(e.message));
  await admin.goto(base + '/admin');
  assert.ok(admin.url().includes('/login?portal=admin'));
  await admin.getByLabel('Username').fill('admin'); await admin.getByLabel('Password', { exact: true }).fill(passwords.admin);
  await admin.getByRole('button', { name: 'Sign in', exact: true }).click();
  await admin.waitForURL('**/admin'); await admin.locator('#adminMenuList .admin-item').first().waitFor();
  assert.equal(await admin.locator('#loginPanel').isVisible(), false);
  await admin.setViewportSize({ width: 1440, height: 1000 });
  await admin.locator('#qrGrid img').evaluateAll(images => Promise.all(images.map(i => i.decode())));
  await admin.locator('.thumb').evaluateAll(images => Promise.all(images.map(i => i.decode().catch(() => {}))));
  await admin.screenshot({ path: 'test-results/admin-desktop.png', fullPage: true });
  const links = await (await adminContext.request.get(base + '/api/table-links')).json();
  await admin.getByRole('button', { name: 'QR flyer' }).click();
  await admin.locator('#flyerQrImage').waitFor();
  await admin.waitForFunction(() => document.getElementById('flyerQrImage').naturalWidth > 0);
  await admin.screenshot({ path: 'test-results/flyer-desktop.png', fullPage: true });
  const guestContext = await browser.newContext(); const guest = await guestContext.newPage();
  guest.on('pageerror', e => errors.push(e.message));
  await guest.goto(links[0].url); await guest.locator('.dish').first().waitFor();
  assert.equal(await guest.getByText('Role login').count(), 0);
  assert.equal(await guest.locator('#logout').isVisible(), false);
  await guest.getByRole('button', { name: 'Add to order', exact: true }).first().click();
  await guest.locator('select[data-field="priority"]').selectOption('first');
  await guest.getByLabel('Name (optional)').fill('Browser verification');
  await guest.setViewportSize({ width: 1440, height: 1000 });
  await guest.locator('.dish img').evaluateAll(images => { images.forEach(i => i.loading = 'eager'); return Promise.all(images.map(i => i.decode())); });
  await guest.screenshot({ path: 'test-results/customer-desktop.png', fullPage: true });
  await guest.setViewportSize({ width: 390, height: 844 });
  await guest.screenshot({ path: 'test-results/customer-mobile.png', fullPage: true });
  assert.equal(await guest.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  const kitchenContext = await browser.newContext(); const kitchen = await kitchenContext.newPage();
  kitchen.on('pageerror', e => errors.push(e.message));
  await kitchen.goto(base + '/kitchen');
  await kitchen.getByLabel('Username').fill('kitchen'); await kitchen.getByLabel('Password', { exact: true }).fill(passwords.kitchen);
  await kitchen.getByRole('button', { name: 'Sign in', exact: true }).click();
  await kitchen.waitForURL('**/kitchen'); await kitchen.getByRole('heading', { name: 'Kitchen orders' }).waitFor();
  await kitchen.screenshot({ path: 'test-results/kitchen-desktop.png', fullPage: true });
  assert.equal((await kitchenContext.request.get(base + '/api/state?portal=admin')).status(), 403);
  await kitchen.setViewportSize({ width: 390, height: 844 });
  await kitchen.screenshot({ path: 'test-results/kitchen-mobile.png', fullPage: true });
  assert.equal(await kitchen.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  await admin.setViewportSize({ width: 390, height: 844 });
  await admin.screenshot({ path: 'test-results/flyer-mobile.png', fullPage: true });
  assert.equal(await admin.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  assert.deepEqual(errors, []);
  console.log('Browser checks passed: separate login, customer cart/priority, local QR, desktop/mobile layout, kitchen access denial, no page errors.');
  await browser.close();
})().catch(e => { console.error(e); process.exit(1); });
